#!/usr/bin/env python3
"""Build the Hrules v2rayN routing rule set from the public Mihomo release tree.

Source of truth (both already generated by publish_public.py):
  - <public>/mihomo/routing.yaml   -> rule order and DIRECT / scene targets
  - <public>/mihomo/scenes/*.yaml  -> rule payloads

Output:
  - <public>/v2rayn/hrules.json    -> JSON array of v2rayN RulesItem objects

Scene outbounds (v0.2)
----------------------
v2rayN resolves a rule's outboundTag that is not proxy/direct/block by looking up
a profile (node, policy group or proxy chain) whose *remarks* equal the tag
(ServiceLib CoreConfig V2rayRoutingService/SingboxRoutingService
GenRoutingUserRuleOutbound, v2rayN 7.25.6). If no such profile exists it falls
back to "proxy" -- never "direct". Hrules therefore emits fixed scene tags:

  * users who create no matching profile get exactly the v0.1 behavior;
  * users who create e.g. a policy group named "Hrules-AI" get scene egress.

Order is preserved exactly, so the DIRECT boundary (private + cn_direct first,
cn IP last) behaves like Mihomo.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

import yaml

VERSION = "v0.2"

# Mihomo routing target -> v2rayN outboundTag.
# Keep the tags plain (no emoji/spaces): users type them as profile remarks.
SCENE_TAGS = {
    "DIRECT": "direct",
    "🤖 AI 服务 [场景]": "Hrules-AI",
    "💳 金融服务 [场景]": "Hrules-金融",
    "📺 流媒体 [场景]": "Hrules-流媒体",
    "🌐 海外应用 [场景]": "proxy",
    "🚀 漏网之鱼 [自选]": "proxy",
}
SCENE_OUTBOUNDS = {"Hrules-AI", "Hrules-金融", "Hrules-流媒体"}

# Scene id -> label shown in v2rayN's rule list.
LABELS = {
    "private_direct": "局域网 / 私有地址",
    "cn_direct": "中国大陆域名",
    "network_test": "IP 检测网站",
    "sensitive_ai": "Claude / OpenAI",
    "general_ai": "通用 AI",
    "apple_intelligence_route": "Apple Intelligence",
    "crypto_account": "虚拟货币",
    "us_banking_account": "美国银行",
    "brokerage_account": "证券 / 券商",
    "financial_account": "支付 / 跨境金融",
    "streaming_media": "流媒体",
    "youtube_media": "YouTube",
    "telegram": "Telegram",
    "apple_private_relay_route": "Apple Private Relay",
    "apple_global": "Apple / iCloud 国际",
    "mainstream_proxy": "海外应用",
}

# Rule providers that are not Hrules scene files.
EXTERNAL = {
    "hrules-cn-ip": {"ip": ["geoip:cn"], "label": "中国大陆 IP"},
}


class BuildError(Exception):
    pass


def parse_rules(routing_path: Path) -> tuple[list[tuple[str, str]], str]:
    doc = yaml.safe_load(routing_path.read_text(encoding="utf-8")) or {}
    order: list[tuple[str, str]] = []
    final = None
    for line in doc.get("rules", []):
        parts = [p.strip() for p in str(line).split(",")]
        if parts[0] == "RULE-SET":
            order.append((parts[1], parts[2]))
        elif parts[0] == "MATCH":
            final = parts[1]
        else:
            raise BuildError(f"routing.yaml: unsupported rule type {parts[0]}")
    if final is None:
        raise BuildError("routing.yaml: MATCH rule missing")
    return order, final


def outbound(target: str) -> str:
    if target not in SCENE_TAGS:
        raise BuildError(f"routing.yaml: no v2rayN outbound for group {target!r}; add it to SCENE_TAGS")
    return SCENE_TAGS[target]


def load_scene(scenes_dir: Path, sid: str) -> tuple[list[str], list[str]]:
    path = scenes_dir / f"{sid}.yaml"
    if not path.exists():
        raise BuildError(f"missing scene file: {path}")
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    domains: list[str] = []
    ips: list[str] = []
    for entry in doc.get("payload", []):
        fields = [f.strip() for f in str(entry).split(",")]
        kind, value = fields[0], fields[1] if len(fields) > 1 else ""
        if kind == "DOMAIN-SUFFIX":
            domains.append(f"domain:{value}")
        elif kind == "DOMAIN":
            domains.append(f"full:{value}")
        elif kind in ("IP-CIDR", "IP-CIDR6"):
            ips.append(value)
        else:
            raise BuildError(f"{path.name}: unsupported rule type {kind} ({value})")
    return domains, ips


def build(public_root: Path) -> list[dict]:
    order, final = parse_rules(public_root / "mihomo" / "routing.yaml")
    scenes_dir = public_root / "mihomo" / "scenes"
    items: list[dict] = []
    for provider, target in order:
        tag = outbound(target)
        if provider in EXTERNAL:
            ext = EXTERNAL[provider]
            items.append({"remarks": f"Hrules·{ext['label']}", "outboundTag": tag, "ip": ext["ip"]})
            continue
        sid = provider.removeprefix("hrules-").replace("-", "_")
        label = LABELS.get(sid)
        if label is None:
            raise BuildError(f"no v2rayN label for scene {sid}; add it to LABELS")
        domains, ips = load_scene(scenes_dir, sid)
        # Xray treats domain + ip in one rule as AND, so keep them separate.
        if domains:
            items.append({"remarks": f"Hrules·{label}", "outboundTag": tag, "domain": domains})
        if ips:
            items.append({"remarks": f"Hrules·{label} IP", "outboundTag": tag, "ip": ips})
    items.append({"remarks": "Hrules·漏网之鱼", "outboundTag": outbound(final), "port": "0-65535"})
    # v2rayN rule sets are bare arrays; carry the version in the first visible remark.
    items[0]["remarks"] = items[0]["remarks"].replace("Hrules·", f"Hrules {VERSION}·", 1)
    validate(items)
    return items


def validate(items: list[dict]) -> None:
    errors: list[str] = []
    allowed = set(SCENE_TAGS.values())
    by_remark = {}
    for i, it in enumerate(items):
        by_remark[it["remarks"].split("·", 1)[1]] = it
        if it["outboundTag"] not in allowed:
            errors.append(f"item {i}: bad outboundTag {it['outboundTag']}")
        if "domain" in it and "ip" in it:
            errors.append(f"item {i}: domain and ip in one rule")
    for required in ("局域网 / 私有地址", "中国大陆域名", "中国大陆 IP"):
        if by_remark.get(required, {}).get("outboundTag") != "direct":
            errors.append(f"DIRECT boundary rule missing or not direct: {required}")
    # IP checks must report the same exit that AI services actually use.
    if by_remark.get("IP 检测网站", {}).get("outboundTag") != by_remark.get("Claude / OpenAI", {}).get("outboundTag"):
        errors.append("IP 检测网站 and Claude / OpenAI must share one outbound")
    last = items[-1]
    if last.get("port") != "0-65535" or last["outboundTag"] != "proxy":
        errors.append("final catch-all must be port 0-65535 -> proxy")
    if any(it["outboundTag"] == "block" for it in items):
        errors.append("Hrules v2rayN must not block traffic")
    if errors:
        raise BuildError("; ".join(errors))


def render(items: list[dict]) -> str:
    return json.dumps(items, ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--public-root", required=True, help="public release tree containing mihomo/routing.yaml and mihomo/scenes")
    p.add_argument("--out", help="output path (default: <public-root>/v2rayn/hrules.json)")
    p.add_argument("--check", action="store_true", help="fail if --out differs from a fresh build")
    args = p.parse_args()
    root = Path(args.public_root)
    out = Path(args.out) if args.out else root / "v2rayn" / "hrules.json"
    try:
        items = build(root)
    except BuildError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    text = render(items)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{out} is stale; rebuild with generators/build_v2rayn.py", file=sys.stderr)
            return 1
        print(f"v2rayN {VERSION} OK")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    d = sum(len(it.get("domain", [])) for it in items)
    n = sum(len(it.get("ip", [])) for it in items)
    print(f"wrote {out}: {len(items)} rules, {d} domains, {n} ip entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
